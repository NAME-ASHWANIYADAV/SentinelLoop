"""Print every number the documents quote, straight from the stored artefacts, as Markdown (docs/NUMBERS.md).

    .venv/Scripts/python.exe experiments/numbers_digest.py [--artifacts artifacts] [--results experiments/results] [--out docs/NUMBERS.md]

The document writers copy from this digest, never from memory; a judge can diff it against the JSON files.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SUBSETS = ["FD001", "FD002", "FD003", "FD004"]


def jl(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, nd=2):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--artifacts", default="artifacts"); ap.add_argument("--results", default="experiments/results"); ap.add_argument("--out", default="docs/NUMBERS.md")
    a = ap.parse_args()
    A, R = ROOT / a.artifacts, ROOT / a.results
    L = ["# Numbers digest (generated by experiments/numbers_digest.py; copy from here, never from memory)", "", f"artifacts: `{a.artifacts}` · results: `{a.results}`", ""]

    # ---- pipeline metrics
    L += ["## Pipeline (`artifacts/<subset>/metrics.json`)", "", "| subset | HGBR RMSE capped / raw | PHM08 | agent model (CQR point) RMSE capped / raw | PICP capped / raw | MPIW | max_width | escalation share | quality flag rate | orders batch + stream | audit records | elapsed s | drift alarm | config hash |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    M = {}
    for s in SUBSETS:
        m = jl(A / s / "metrics.json") or {}
        M[s] = m
        L.append(f"| {s} | {f(m.get('hgbr_rmse_capped'))} / {f(m.get('hgbr_rmse_raw'))} | {f(m.get('hgbr_phm08'), 0)} | {f(m.get('cqr_point_rmse_capped'))} / {f(m.get('cqr_point_rmse_raw'))} | {f(m.get('picp_test_capped'), 3)} / {f(m.get('picp_test_raw'), 3)} | {f(m.get('mpiw_test'), 1)} | {f(m.get('agent_max_width'), 1)} | {f(m.get('escalation_share_test'), 3)} | {f(m.get('quality_flag_rate_test'), 3)} | {m.get('n_work_orders_batch')} + {m.get('n_work_orders_stream')} | {m.get('audit_records')} | {m.get('elapsed_s')} | {m.get('drift_alarm_test')} | {m.get('config_hash')} |")
    L += ["", "Severity counts and decision outcomes vs true RUL (official test engines):", ""]
    for s in SUBSETS:
        m = M[s]
        oc = m.get("decision_outcomes_test") or {}
        L.append(f"- {s}: severities {m.get('severity_counts_test')}; lower bound above truth {f(oc.get('lower_bound_above_truth_rate'), 3)}; serious truth (<= t_high) missed {f(oc.get('serious_truth_missed_rate'), 3)}; confident order on healthy (> t_medium) {oc.get('confident_order_on_healthy_count')} engines ({f(oc.get('confident_order_on_healthy_rate'), 3)}); anomaly flag rate by true-RUL band {oc.get('anomaly_flag_rate_by_band')}; counts {oc.get('counts')}")
    L += ["", f"Dropped sensors: " + "; ".join(f"{s}: {M[s].get('dropped_sensors')} (n_features {M[s].get('n_features')})" for s in SUBSETS), ""]

    # ---- E0
    L += ["## E0 baseline (`artifacts/baseline/<subset>/metrics.json`)", "", "| subset | HGBR capped / raw | PHM08 | RF capped | naive capped | CV all rows | CV random truncation (honest) | CV last cycle (leaky) | ratio leaky→honest | elapsed s | config hash |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in SUBSETS:
        b = jl(A / "baseline" / s / "metrics.json") or jl(R / "e0_baseline" / f"{s}_metrics.json") or {}
        lk, ho = b.get("cv_rmse_last_cycle_naive_protocol"), b.get("cv_rmse_random_truncation_protocol")
        L.append(f"| {s} | {f(b.get('hgbr_rmse_capped'))} / {f(b.get('hgbr_rmse_raw'))} | {f(b.get('hgbr_phm08'), 0)} | {f(b.get('rf_rmse_capped'))} | {f(b.get('naive_rmse_capped'))} | {f(b.get('cv_rmse_all_rows'))} | {f(ho)} | {f(lk)} | {f(ho / lk if lk else None, 1)}x | {b.get('elapsed_s')} | {b.get('config_hash')} |")
    L.append("")

    # ---- E1
    e1 = jl(R / "e1_policy_replay" / "summary.json")
    if e1:
        L += ["## E1 policy replay", "", e1["conclusion"], "", "| subset | policy | threshold | margin | late rate | mean discarded | n late | churn | order rate | early rate |", "|---|---|---|---|---|---|---|---|---|---|"]
        for r in e1["table"]:
            L.append(f"| {r['subset']} | {r['policy']} | {r.get('threshold')} | {r.get('margin')} | {f(r['late_rate'], 3)} | {f(r['mean_discarded_life'], 1)} | {r.get('n_late')} | {f(r.get('churn'), 2)} | {f(r.get('order_rate'), 3)} | {f(r.get('early_rate'), 3)} |")
        t = pd.DataFrame(e1["table"])
        gaps = {s: float(t[(t.subset == s) & (t.policy == "C_lower_T")]["mean_discarded_life"].iloc[0] - t[(t.subset == s) & (t.policy == "A_point_T")]["mean_discarded_life"].iloc[0]) for s in SUBSETS if ((t.subset == s) & (t.policy == "C_lower_T")).any()}
        L += ["", f"Discarded-life gap C_lower_T minus A_point_T per subset: {{{', '.join(f'{k}: {v:.2f}' for k, v in gaps.items())}}} → range {min(gaps.values()):.1f}–{max(gaps.values()):.1f}", ""]
        fr = pd.DataFrame(e1["frontier"])
        L += ["Frontier (A-family vs C-family at matched late-rate targets):", "", "| subset | target | A thr | A late | A discarded | C thr | C late | C discarded | C better or equal | C dominated | C discarded minus A |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in fr.iterrows():
            L.append(f"| {r['subset']} | {r['target_late_rate']} | {r['A_threshold']} | {f(r['A_late_eval'], 3)} | {f(r['A_discarded_eval'], 1)} | {r['C_threshold']} | {f(r['C_late_eval'], 3)} | {f(r['C_discarded_eval'], 1)} | {r['C_better_or_equal']} | {r['C_dominated']} | {f(r['C_discarded_eval'] - r['A_discarded_eval'], 2)} |")
        lower_late = fr[fr["C_late_eval"] < fr["A_late_eval"]]
        L += ["", f"Frontier counts: {int(fr['C_better_or_equal'].sum())}/{len(fr)} C better or equal on both; {int(fr['C_dominated'].sum())}/{len(fr)} C dominated; C lower late rate at {len(lower_late)}/{len(fr)} points with discarded-life cost {f(lower_late['C_discarded_eval'].sub(lower_late['A_discarded_eval']).min(), 2)} to {f(lower_late['C_discarded_eval'].sub(lower_late['A_discarded_eval']).max(), 2)}", ""]
        for s, v in e1["verdicts"].items():
            L.append(f"- verdict {s}: {json.dumps(v, default=str)[:600]}")
        L.append("")

    # ---- E1 seed sensitivity
    e1s = jl(R / "e1_seed_sensitivity" / "summary.json")
    if e1s:
        L += ["## E1 seed sensitivity (post hoc)", "", e1s["conclusion"], "", "| subset | seed | A@25 late | A@25 discarded | C@25 late | C@25 discarded | gap | tuned C thr | tuned C late | tuned C discarded | tuned A thr | tuned A late | tuned A discarded |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in e1s["table"]:
            L.append(f"| {r['subset']} | {r['seed']} | {f(r['A_point_T_late'], 3)} | {f(r['A_point_T_discarded'], 1)} | {f(r['C_lower_T_late'], 3)} | {f(r['C_lower_T_discarded'], 1)} | {f(r['gap_discarded_C_minus_A_at_T'], 1)} | {r['C_lower_tuned_threshold']} | {f(r['C_lower_tuned_late'], 3)} | {f(r['C_lower_tuned_discarded'], 1)} | {r['A_point_tuned_threshold']} | {f(r['A_point_tuned_late'], 3)} | {f(r['A_point_tuned_discarded'], 1)} |")
        L.append("")

    # ---- E2
    e2 = jl(R / "e2_abstention" / "summary.json")
    if e2:
        L += ["## E2 abstention", "", e2["conclusion"], "", "| subset | n eval | error rate all | error rate acted upon | error rate escalated | relative change | escalation share |", "|---|---|---|---|---|---|---|"]
        for r in e2["table"]:
            L.append(f"| {r['subset']} | {r['n_eval']} | {f(r['error_rate_all_decisions'], 3)} | {f(r['error_rate_acted_upon'], 3)} | {f(r['error_rate_among_escalated'], 3)} | {f(r['relative_reduction'], 3)} | {f(r['escalation_share'], 3)} |")
        L.append("")

    # ---- E3
    e3 = jl(R / "e3_stress" / "summary.json")
    if e3:
        L += ["## E3 stress", "", e3["conclusion"], "", "| subset | fault | detection | false alarm | by quality | by new anomaly | silent wrong naive | silent wrong full | silent wrong full, no fleet rule | escalation corrupted | escalation clean (fleet rule on) | escalation clean (clean run) | fleet alarm mixed tail | fleet alarm clean early | reasons |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in e3["table"]:
            L.append(f"| {r['subset']} | {r['fault']} | {f(r['detection_rate'], 3)} | {f(r['false_alarm_rate'], 3)} | {f(r['detect_by_quality'], 3)} | {f(r['detect_by_new_anomaly'], 3)} | {f(r['silent_wrong_order_naive'], 3)} | {f(r['silent_wrong_order_full'], 3)} | {f(r.get('silent_wrong_order_full_no_fleet_rule'), 3)} | {f(r['escalation_share_full_corrupted'], 3)} | {f(r.get('escalation_share_full_clean'), 3)} | {f(r.get('escalation_share_base_clean'), 3)} | {r['fleet_drift_alarm_mixed_tail']} | {r['fleet_drift_alarm_clean_early']} | {r.get('fleet_drift_reasons')} |")
        t = pd.DataFrame(e3["table"])
        for fault, g in t.groupby("fault"):
            L.append(f"- {fault}: detection {g['detection_rate'].min():.2f}–{g['detection_rate'].max():.2f}; false alarm {g['false_alarm_rate'].min():.2f}–{g['false_alarm_rate'].max():.2f}; naive silent wrong {g['silent_wrong_order_naive'].min():.3f}–{g['silent_wrong_order_naive'].max():.3f}; escalation corrupted {g['escalation_share_full_corrupted'].min():.2f}–{g['escalation_share_full_corrupted'].max():.2f}")
        nz = t[t["silent_wrong_order_naive"] > 0]
        L += [f"- naive silent-wrong-order over all 20 rows: {t['silent_wrong_order_naive'].min():.3f}–{t['silent_wrong_order_naive'].max():.3f} ({int((t['silent_wrong_order_naive'] == 0).sum())} rows at 0); full agent: {t['silent_wrong_order_full'].min():.3f}–{t['silent_wrong_order_full'].max():.3f}; full without fleet rule: {f(t['silent_wrong_order_full_no_fleet_rule'].min() if 'silent_wrong_order_full_no_fleet_rule' in t else None, 3)}–{f(t['silent_wrong_order_full_no_fleet_rule'].max() if 'silent_wrong_order_full_no_fleet_rule' in t else None, 3)}",
              f"- escalation share on corrupted engines over all rows: {t['escalation_share_full_corrupted'].min():.2f}–{t['escalation_share_full_corrupted'].max():.2f}; clean engines with the fleet rule on: {f(t['escalation_share_full_clean'].min() if 'escalation_share_full_clean' in t else None)}–{f(t['escalation_share_full_clean'].max() if 'escalation_share_full_clean' in t else None)}; clean run: {f(t['escalation_share_base_clean'].min() if 'escalation_share_base_clean' in t else None)}–{f(t['escalation_share_base_clean'].max() if 'escalation_share_base_clean' in t else None)}",
              f"- fleet alarm clean-early true on: {sorted(set(t[t['fleet_drift_alarm_clean_early']]['subset']))}; mixed-tail true on {int(t['fleet_drift_alarm_mixed_tail'].sum())}/{len(t)} rows", ""]

    # ---- E4
    for name in ("e4_retrain_gate", "e4_retrain_gate_secondary"):
        e4 = jl(R / name / "summary.json")
        if e4:
            L += [f"## {name}", "", e4["conclusion"], f"val rows per engine {e4.get('val_rows_per_engine')}, label corruption {e4.get('label_corruption_scenario')}", "", "| subset | scenario | expected | decision | champion rmse → challenger | champion picp → challenger | late@crit champion → challenger | late@high champion → challenger | reasons |", "|---|---|---|---|---|---|---|---|---|"]
            for r in e4["table"]:
                L.append(f"| {r['subset']} | {r['scenario']} | {r['expected']} | {r['decision']} | {f(r['champion_rmse'])} → {f(r['challenger_rmse'])} | {f(r['champion_picp'], 3)} → {f(r['challenger_picp'], 3)} | {f(r['champion_late_rate'], 3)} → {f(r['challenger_late_rate'], 3)} | {f(r.get('champion_late_rate_high'), 3)} → {f(r.get('challenger_late_rate_high'), 3)} | {r['reasons']} |")
            L.append("")
            for s, dd in e4["drift"].items():
                L.append(f"- drift {s}: {dd}")
            L.append("")

    # ---- E5
    e5 = jl(R / "e5_decision_vs_rmse" / "summary.json")
    if e5:
        L += ["## E5 decision metrics vs RMSE", "", e5["conclusion"], "", "| subset | model | RMSE | late | discarded | early |", "|---|---|---|---|---|---|"]
        for r in e5["table"]:
            L.append(f"| {r['subset']} | {r['model']} | {f(r['rmse_eval_random_truncation'])} | {f(r['late_rate'], 3)} | {f(r['mean_discarded_life'], 1)} | {f(r['early_rate'], 3)} |")
        t = pd.DataFrame(e5["table"])
        pts = ["random_forest", "hgbr_all_fold_engines", "hgbr_70pct_point"]
        diffs = []
        for s, g in t.groupby("subset"):
            g = g[g.model.isin(pts)].sort_values("rmse_eval_random_truncation")
            for i in range(len(g)):
                for j in range(i + 1, len(g)):
                    ra, rb = g.iloc[i], g.iloc[j]
                    diffs.append((s, ra.model, rb.model, float(ra.mean_discarded_life - rb.mean_discarded_life)))
        inv = [d for d in diffs if d[3] > 1e-9]
        L += ["", f"Point-model pairs (better RMSE minus worse RMSE, discarded life): {len(inv)}/{len(diffs)} positive (better-RMSE model discards more), " + "; ".join(f"{s} {a}>{b}: {d:+.2f}" for s, a, b, d in diffs), ""]
        for s, g in t.groupby("subset"):
            lo = g[g.model == "hgbr_cqr_lower_bound"].iloc[0]; pt = g[g.model == "hgbr_70pct_point"].iloc[0]
            L.append(f"- {s}: lower-bound row discards {lo.mean_discarded_life - pt.mean_discarded_life:+.2f} vs its point model (late {pt.late_rate:.3f} → {lo.late_rate:.3f}); RF RMSE {f(g[g.model == 'random_forest'].iloc[0].rmse_eval_random_truncation)} discards {f(g[g.model == 'random_forest'].iloc[0].mean_discarded_life, 1)}")
        L.append("")

    # ---- E6, E7
    e6 = jl(R / "e6_audit_check" / "summary.json")
    if e6:
        L += ["## E6 audit", "", e6["conclusion"], f"replay: {e6.get('replay')}", f"per log: {e6.get('per_log')}", f"tampered: {e6.get('tampered')}", f"orders: {e6.get('n_orders')} traceable {e6.get('orders_traceable')}", ""]
    e7 = jl(R / "e7_ablation" / "summary.json")
    if e7:
        L += ["## E7 ablation", "", "| subset | variant | n features | test RMSE capped / raw | PICP | MPIW | holdout late / discarded (point) | (lower) |", "|---|---|---|---|---|---|---|---|"]
        for r in e7["table"]:
            L.append(f"| {r['subset']} | {r['variant']} | {r['n_features']} | {f(r['test_rmse_capped'])} / {f(r['test_rmse_raw'])} | {f(r['test_picp'], 3)} | {f(r['test_mpiw'], 1)} | {f(r['holdout_late_rate_point'], 3)} / {f(r['holdout_discarded_point'], 1)} | {f(r['holdout_late_rate_lower'], 3)} / {f(r['holdout_discarded_lower'], 1)} |")
        L.append("")

    # ---- run log wall time
    log = R / "run_all_phase6.log"
    if log.exists():
        lines = [l for l in log.read_text(encoding="utf-8", errors="replace").splitlines() if "ALL DONE" in l or "-> exit" in l]
        L += ["## run_all.py", ""] + [f"- {l.strip()}" for l in lines[-40:]] + [""]
    (ROOT / a.out).write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {ROOT / a.out} ({len(L)} lines)")


if __name__ == "__main__":
    main()
