def test_ambient_temperature_outside_training_range_is_out_of_scope(plant, fleet):
    pol = policymod.load(ROOT / "configs" / "platform.yaml")
    t = fleet.meta["start_ms"] + int(9 * DAY_MS)        # a windy day: the only reason to be out of scope is the climate
    plant_turbine = "WT02"

    def freeze(s):
        s = s.copy()
        shift = 45.0
        for c in ("ambient_temp", "nacelle_temp", "gearbox_oil_temp", "gearbox_bearing_temp", "generator_bearing_temp"):
            s[c] = s[c] - shift
        return s
    _ingest_window(plant, fleet, plant_turbine, t, mutate=freeze)
    a = health.assess(plant, plant_turbine, pol, as_of_ms=t, actor="svc")
    assert a["health_state"] == "MODEL_OUT_OF_SCOPE" and any("operating_envelope" in r for r in a["reasons"])
    assert not any("insufficient_operation" in r for r in a["reasons"])


def test_generator_and_rotor_speed_disagreement_is_a_data_quality_failure(plant, fleet):
    pol = policymod.load(ROOT / "configs" / "platform.yaml")
    t = fleet.meta["start_ms"] + int(18 * DAY_MS)

    def bad_speed(s):
        s = s.copy()
        s.loc[s.ts_ms > t - 6 * HOUR_MS, "generator_speed"] = s.loc[s.ts_ms > t - 6 * HOUR_MS, "generator_speed"] * 0.6
        return s
