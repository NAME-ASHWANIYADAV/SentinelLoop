def test_generator_is_deterministic_labelled_and_physically_plausible(fleet):
    again = sw.generate(sw.FleetSpec(n_turbines=4, days=36, seed=11, faults=(FAULT,)))
    pd.testing.assert_frame_equal(fleet.scada, again.scada)
    assert fleet.meta["data_class"] == "SYNTHETIC"
    assert set(wind.SIGNALS) <= set(fleet.scada.columns) and {"turbine", "ts_ms"} <= set(fleet.scada.columns)
    lab = fleet.labels
    assert len(lab) == 1 and lab[0]["turbine"] == "WT03" and lab[0]["component"] == "hss_bearing"
    s = fleet.scada
    assert (s["active_power"] <= wind.RATED_KW * 1.02 + 1e-9).all()
    below_cut_in = s[s["wind_speed"] < 2.5]
    assert (below_cut_in["active_power"] < 0.02 * wind.RATED_KW).mean() > 0.95
    assert s.groupby("turbine")["ts_ms"].diff().dropna().eq(10 * 60 * 1000).all()     # 10-minute grid


def test_injected_bearing_fault_raises_bearing_temperature_relative_to_power(fleet):
    s = fleet.scada
    late = s[(s.ts_ms >= fleet.meta["start_ms"] + int(31 * DAY_MS)) & (s.ts_ms < fleet.meta["start_ms"] + int(34 * DAY_MS)) & (s.active_power > 800)]
    excess = (late.gearbox_bearing_temp - late.ambient_temp).groupby(late.turbine).mean()
    assert excess["WT03"] > excess.drop("WT03").max() + 4.0


def test_sensor_fault_injection_is_labelled():
    g = sw.generate(sw.FleetSpec(n_turbines=2, days=6, seed=5, sensor_faults=(
        sw.SensorFault("WT01", "gearbox_oil_temp", "stuck", start_day=3.0, end_day=4.0),
        sw.SensorFault("WT02", "generator_bearing_temp", "dropout", start_day=2.0, end_day=2.5))))
    s = g.scada.set_index(["turbine", "ts_ms"])
    st = g.meta["start_ms"]
    stuck = s.loc["WT01"].loc[st + 3 * DAY_MS + HOUR_MS: st + 4 * DAY_MS - HOUR_MS, "gearbox_oil_temp"]
    assert stuck.nunique() == 1
    drop = s.loc["WT02"].loc[st + 2 * DAY_MS + HOUR_MS: st + 2.5 * DAY_MS - HOUR_MS, "generator_bearing_temp"]
    assert drop.isna().all()
    assert {x["kind"] for x in g.sensor_fault_labels} == {"stuck", "dropout"}


def test_normal_behaviour_model_flags_the_fault_before_failure_and_stays_quiet_on_healthy_turbines(bundle_dir, fleet):
    b = nbm.load(bundle_dir)
    ev = nbm.evaluate(b, fleet.scada, fleet.labels, step_points=6, baseline_days=7)      # each turbine commissioned on its first 7 days
    wt3 = ev["per_turbine"]["WT03"]
    det = ev["detections"][0]
    assert det["detected"] and det["lead_days"] >= 2.0, det          # flagged at least two days before the injected failure
    assert det["alarms_before_onset"] == 0 and wt3["first_alarm_ms"] >= fleet.labels[0]["fault_start_ms"]   # and not before the fault exists
    for t in ("WT01", "WT02", "WT04"):
        assert ev["per_turbine"][t]["alarm_points"] == 0, (t, ev["per_turbine"][t])
    m = nbm.read_manifest(bundle_dir)
    assert m["prediction_kind"] == "anomaly" and m["trained_on"]["data_class"] == "SYNTHETIC"
    assert "healthy_validation_alarm_rate" in m["evaluation"]


def test_anomaly_only_classification_never_invents_a_probability():
    thr = states.Thresholds()
    c = states.classify(True, True, True, None, sustained_anomaly=False, thr=thr, anomaly_only=True)
    assert c.state == states.HealthState.NORMAL_MONITORING
    c = states.classify(True, True, True, None, sustained_anomaly=True, thr=thr, anomaly_only=True)
    assert c.state == states.HealthState.INSPECTION_RECOMMENDED and "no failure-time estimate" in " ".join(c.reasons)
    c = states.classify(True, True, True, None, sustained_anomaly=True, thr=thr, anomaly_only=True, severe_anomaly=True)
    assert c.state == states.HealthState.URGENT_REVIEW
    with pytest.raises(ValueError):
        states.classify(True, True, True, None, sustained_anomaly=False, thr=thr)          # a RUL model must carry a probability


def test_baseline_offsets_absorb_turbine_differences_but_not_a_developing_fault(bundle_dir, fleet):
    b = nbm.load(bundle_dir)
    raw = nbm.evaluate(b, fleet.scada, fleet.labels, step_points=6, baseline_days=None)   # no commissioning: fleet model only
    assert sum(v["alarm_points"] for k, v in raw["per_turbine"].items() if k != "WT03") > 0    # the fleet model alone false-alarms
    with pytest.raises(ValueError):
        nbm.evaluate(b, fleet.scada, fleet.labels, baseline_days=25)         # a baseline may not overlap a labelled fault


