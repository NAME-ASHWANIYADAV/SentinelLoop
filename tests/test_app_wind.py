def _ingest_window(d, fleet, turbine, end_ms, hours=24, mutate=None):
    s = fleet.scada[(fleet.scada.turbine == turbine) & (fleet.scada.ts_ms > end_ms - hours * HOUR_MS) & (fleet.scada.ts_ms <= end_ms)].copy()
    if mutate:
        s = mutate(s)
    recs = wind.records(s)
    r = ingest.ingest_records(d, recs, source="synthetic-scada", actor="svc", now_ms=end_ms + 60_000)
    assert r.rows_rejected == 0, r.to_dict()["errors"][:3]


def test_end_to_end_fault_becomes_a_p1_inspection_without_an_invented_probability(plant, fleet):
    pol = policymod.load(ROOT / "configs" / "platform.yaml")
    st = fleet.meta["start_ms"]
    t_ok = st + int(10 * DAY_MS)
    _ingest_window(plant, fleet, "WT03", t_ok)
    a = health.assess(plant, "WT03", pol, as_of_ms=t_ok, actor="svc")
    assert a["health_state"] == "NORMAL_MONITORING", a["reasons"]
    assert a["rul_point"] is None and a["risk"] == {}
    t_bad = st + int(33 * DAY_MS)
    _ingest_window(plant, fleet, "WT03", t_bad)
    a = health.assess(plant, "WT03", pol, as_of_ms=t_bad, actor="svc")
    assert a["health_state"] in ("INSPECTION_RECOMMENDED", "URGENT_REVIEW"), a["reasons"]
    assert a["risk"] == {} and a["top_deviations"] and a["top_deviations"][0][0] == "gearbox_bearing_temp"
    out = decision.generate(plant, decision.DecisionConfig(), actor="svc", now_ms=t_bad)
    created = [x for x in out if x["asset_id"] == "WT03"]
    assert created and created[0]["action"] == "created", out
    wo = workorders.get(plant, created[0]["wo_id"])
    assert wo["job_type"] == "inspect"                       # an anomaly never turns into a repair by itself
    assert wo["explanation"]["p_fail_decision_horizon"] is None and wo["explanation"]["rul_hours"] is None
    assert wo["priority_class"] == ("P1" if a["health_state"] == "URGENT_REVIEW" else "P2")


@pytest.mark.parametrize("day", [18, 12])           # day 18: windy, turbine producing; day 12: calm, turbine mostly idle
def test_stuck_temperature_sensor_is_a_data_quality_failure_not_an_anomaly(plant, fleet, day):
    pol = policymod.load(ROOT / "configs" / "platform.yaml")
    t = fleet.meta["start_ms"] + int(day * DAY_MS)

    def stick(s):
        s = s.copy()
        s.loc[s.ts_ms > t - 8 * HOUR_MS, "gearbox_oil_temp"] = 51.3
        return s
    _ingest_window(plant, fleet, "WT01", t, mutate=stick)
    a = health.assess(plant, "WT01", pol, as_of_ms=t, actor="svc")
    assert a["health_state"] == "DATA_QUALITY_FAILURE" and any("stuck_signal:gearbox_oil_temp" in r for r in a["reasons"]), a["reasons"]


